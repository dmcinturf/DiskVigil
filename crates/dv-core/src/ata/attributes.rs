//! SMART attribute knowledge base (names, descriptions, criticality).
//!
//! Attribute meaning is not fully standardised; where HDDs and SSDs disagree the
//! `ssd` flag picks the more common interpretation for that class of drive.

pub struct AttrMeta {
    pub name: &'static str,
    pub description: &'static str,
    /// A non-zero raw value is a sign of media / reliability problems.
    pub critical: bool,
}

const fn m(name: &'static str, description: &'static str, critical: bool) -> AttrMeta {
    AttrMeta {
        name,
        description,
        critical,
    }
}

